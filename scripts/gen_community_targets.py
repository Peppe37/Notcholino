#!/usr/bin/env python3
"""Writes community/targets.yml: the build targets of the community plugins and extensions, made from their plugin.json.

A contributor adds a folder with a plugin.json and Swift files, and nothing else: the target is generated here, from a fixed
template, so a pull request cannot add a build script, a dependency or a build setting. `--check` fails if the file is stale.
Run it before `xcodegen generate` (the workflows do)."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import store_items

OUT = os.path.join(store_items.ROOT, "community", "targets.yml")


def render():
    lines = ["# Generated by scripts/gen_community_targets.py from community/*/*/plugin.json. Do not edit.", "targets:"]
    found = False
    for it in store_items.items():
        if it["official"] or not it["meta"]:
            continue
        m = it["meta"]
        api = "ExtensionAPI" if it["kind"] == "extension" else "Shared"
        found = True
        lines += [
            f"  {m['target']}:",
            "    type: bundle",
            "    platform: macOS",
            '    deploymentTarget: "14.0"',
            "    sources:",
            # Paths in an included file are relative to that file (community/)
            f"      - {it['rel'][len('community/'):]}",
            f"      - ../{api}",
            "    settings:",
            "      base:",
            "        GENERATE_INFOPLIST_FILE: YES",
            f"        INFOPLIST_KEY_NSPrincipalClass: {m['principalClass']}",
            f"        MARKETING_VERSION: \"{m['version']}\"",
            f"        PRODUCT_BUNDLE_IDENTIFIER: dev.notcholino.community.{m['id']}",
            '        CODE_SIGN_IDENTITY: "-"',
        ]
    if not found:
        lines[-1] = "targets: {}"
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.isfile(OUT) else ""
        if current != text:
            sys.exit("community/targets.yml is out of date: run python3 scripts/gen_community_targets.py")
        print("community/targets.yml is up to date")
    else:
        open(OUT, "w").write(text)
        print(f"wrote {OUT}")
