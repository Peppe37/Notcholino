import AppKit
import Foundation

/// Clippy remembers the last things you copied (text, images, files) so you can copy one again with a click.
///
/// It only keeps them in memory: nothing is written to disk, and everything is forgotten when Notcholino quits.
/// What password managers mark as secret or temporary is never kept.
@objc(ClippyPlugin)
final class ClippyPlugin: NSObject, NotcholinoPlugin {

    // MARK: Plugin info

    var apiVersion: Int { notcholinoPluginAPIVersion }
    var pluginIdentifier: String { "clippy" }
    var pluginName: String { "Clippy" }
    var pluginVersion: String {
        Bundle(for: ClippyPlugin.self).infoDictionary?["CFBundleShortVersionString"] as? String ?? "0"
    }
    var pluginAuthor: String { "Giuseppe" }
    var pluginDescription: String { "The last things you copied, to copy again with a click. Kept in memory only, never on disk." }

    // MARK: History

    private enum Entry {
        case text(String)
        case image(NSImage, label: String)
        case files([URL])

        var title: String {
            switch self {
            case .text(let s):
                let flat = s.components(separatedBy: .newlines).map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }.joined(separator: " ")
                return flat.count > 60 ? String(flat.prefix(60)) + "…" : flat
            case .image(_, let label): return "🖼  " + label
            case .files(let urls): return "📄  " + (urls.count == 1 ? urls[0].lastPathComponent : "\(urls[0].lastPathComponent) and \(urls.count - 1) more")
            }
        }

        /// Whether two entries are the same copy (so that copying something again moves it to the top)
        func matches(_ other: Entry) -> Bool {
            switch (self, other) {
            case (.text(let a), .text(let b)): return a == b
            case (.files(let a), .files(let b)): return a == b
            case (.image(_, let a), .image(_, let b)): return a == b
            default: return false
            }
        }
    }

    private static let limit = 10
    private static let ignoredTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                       "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]

    private var entries: [Entry] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    override init() {
        super.init()
        let t = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.check() }
        t.tolerance = 0.5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func pluginWillUnload() { timer?.invalidate(); timer = nil; entries = [] }

    private func check() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let entry: Entry?
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            entry = .files(urls)
        } else if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            entry = .text(text)
        } else if let image = NSImage(pasteboard: board) {
            entry = .image(image, label: "Image \(Int(image.size.width))×\(Int(image.size.height))")
        } else {
            entry = nil
        }
        guard let entry else { return }
        entries.removeAll { $0.matches(entry) }
        entries.insert(entry, at: 0)
        if entries.count > Self.limit { entries.removeLast(entries.count - Self.limit) }
    }

    // MARK: Control Center

    var isActive: Bool { false }
    var controlCenterIcon: String { "doc.on.clipboard" }
    var statusText: String { entries.isEmpty ? "" : "\(entries.count) saved" }

    func menuItems() -> [[String: Any]] {
        check()
        guard !entries.isEmpty else { return [["header": "Nothing copied yet. What you copy from now on shows up here."]] }
        var items: [[String: Any]] = [["header": "Click to copy again"]]
        for (i, entry) in entries.enumerated() {
            items.append(["id": "copy:\(i)", "title": entry.title, "wide": true])
        }
        items.append(["id": "clear", "title": "Clear", "destructive": true])
        return items
    }

    func performMenuAction(_ id: String) {
        if id == "clear" { entries = []; return }
        guard id.hasPrefix("copy:"), let i = Int(id.dropFirst(5)), entries.indices.contains(i) else { return }
        let board = NSPasteboard.general
        board.clearContents()
        switch entries[i] {
        case .text(let s): board.setString(s, forType: .string)
        case .image(let image, _): board.writeObjects([image])
        case .files(let urls): board.writeObjects(urls as [NSURL])
        }
        // Our own copy isn't a new one
        lastChange = board.changeCount
        let entry = entries.remove(at: i)
        entries.insert(entry, at: 0)
    }
}
