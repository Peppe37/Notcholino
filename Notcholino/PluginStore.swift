import AppKit
import CryptoKit
import Foundation

/// A plugin listed in the store manifest (plugins.json on the project website)
struct RemotePlugin: Decodable, Identifiable {
    let id: String
    let name: String
    let description: String
    let author: String
    let icon: String
    let version: String
    let url: URL
    let sha256: String
    /// Oldest Notcholino that can run it, e.g. "0.8.0"
    let minAppVersion: String?
    // The store page (all optional: an older manifest has none of it)
    let details: String?
    let features: [String]?
    let permissions: String?
    let whatsNew: [String]?
    let screenshots: [URL]?
    let video: URL?
    /// One of the shelves of the store ("System", "Productivity"...), and the words people may search for
    let category: String?
    let tags: [String]?

    /// What the store search looks at: name, description, features, category and tags
    var searchText: String {
        ([name, description, details ?? "", category ?? ""] + (features ?? []) + (tags ?? [])).joined(separator: " ").lowercased()
    }

    func matches(_ query: String) -> Bool {
        let words = query.lowercased().split(separator: " ").map(String.init)
        guard !words.isEmpty else { return true }
        let text = searchText
        return words.allSatisfy { text.contains($0) }
    }

    /// True if this version of the app is new enough
    var isCompatible: Bool {
        guard let min = minAppVersion else { return true }
        let current = Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String ?? "0"
        return RemotePlugin.compare(current, min) != .orderedAscending
    }

    /// Compares dotted numbers, ignoring a suffix like "-alpha"
    static func compare(_ a: String, _ b: String) -> ComparisonResult {
        func parts(_ v: String) -> [Int] { v.split(separator: "-").first.map { $0.split(separator: ".").map { Int($0) ?? 0 } } ?? [] }
        let x = parts(a), y = parts(b)
        for i in 0..<max(x.count, y.count) {
            let l = i < x.count ? x[i] : 0, r = i < y.count ? y[i] : 0
            if l != r { return l < r ? .orderedAscending : .orderedDescending }
        }
        return .orderedSame
    }
}

private struct PluginManifest: Decodable {
    let apiVersion: Int
    let plugins: [RemotePlugin]
}

/// Downloads plugins from the project's GitHub releases.
/// The manifest is generated by the release pipeline and always points to each plugin's latest release.
@MainActor
final class PluginStore: ObservableObject {
    static let shared = PluginStore()

    static let manifestURL = URL(string: "https://peppe37.github.io/Notcholino/plugins.json")!
    /// Plugins are only ever downloaded from this repository's releases
    static let allowedPrefix = "https://github.com/Peppe37/Notcholino/releases/download/"

    @Published private(set) var available: [RemotePlugin] = []
    @Published private(set) var isLoading = false
    @Published private(set) var busyID: String?
    @Published var message: String?

    private var pluginManager: PluginManager { .shared }

    func refresh() async {
        isLoading = true
        defer { isLoading = false }
        do {
            let (data, response) = try await URLSession.shared.data(from: Self.manifestURL)
            guard (response as? HTTPURLResponse)?.statusCode == 200 else {
                throw StoreError.message("The plugin list is not available yet.")
            }
            let manifest = try JSONDecoder().decode(PluginManifest.self, from: data)
            guard manifest.apiVersion == notcholinoPluginAPIVersion else {
                throw StoreError.message("The plugin list needs a newer version of Notcholino.")
            }
            available = manifest.plugins
            message = nil
        } catch {
            message = (error as? StoreError)?.text ?? "Could not load the plugin list. Check your connection."
        }
    }

    func installedVersion(of id: String) -> String? {
        pluginManager.loadedPlugins.first { $0.pluginIdentifier == id }?.pluginVersion
    }

    /// Asks for confirmation, then downloads, verifies and installs the plugin
    /// Plugins installed here with a newer version in the store that this app can run
    var updates: [RemotePlugin] {
        available.filter { p in
            guard let v = installedVersion(of: p.id) else { return false }
            return v != p.version && p.isCompatible
        }
    }

    /// Set while an update is on disk but the old code still runs: the app has to restart to use it
    private var needsRestart: [String] = []

    func install(_ plugin: RemotePlugin) async {
        guard busyID == nil else { return }
        guard plugin.isCompatible else {
            message = "\(plugin.name) needs Notcholino \(plugin.minAppVersion ?? "") or later. Update the app first."
            return
        }
        guard confirmInstall(plugin) else { return }
        busyID = plugin.id
        defer { busyID = nil }
        do {
            try await performInstall(plugin)
            if !needsRestart.isEmpty { finishUpdates() }
        } catch {
            message = (error as? StoreError)?.text ?? "Installing \(plugin.name) failed: \(error.localizedDescription)"
        }
    }

    /// Updates every plugin that has a newer version, with one question at the start and one restart at the end
    func updateAll() async {
        let list = updates
        guard !list.isEmpty, busyID == nil else { return }
        let alert = NSAlert()
        alert.messageText = "Update \(list.count) plugin\(list.count == 1 ? "" : "s")?"
        alert.informativeText = list.map { "• \($0.name) \($0.version)" }.joined(separator: "\n")
            + "\n\nThey are downloaded from the Notcholino releases on GitHub and checked against their published checksums. Notcholino restarts afterwards (about a second)."
        alert.addButton(withTitle: "Update and restart")
        alert.addButton(withTitle: "Cancel")
        NSApp.activate(ignoringOtherApps: true)
        guard alert.runModal() == .alertFirstButtonReturn else { return }
        var failed: [String] = []
        for plugin in list {
            busyID = plugin.id
            do { try await performInstall(plugin) } catch { failed.append(plugin.name) }
        }
        busyID = nil
        if !failed.isEmpty { message = "Could not update: \(failed.joined(separator: ", "))." }
        if !needsRestart.isEmpty { relaunch() }
    }

    private func finishUpdates() {
        let names = needsRestart
        needsRestart = []
        let alert = NSAlert()
        alert.messageText = "Restart Notcholino to finish updating \(names.joined(separator: ", "))?"
        alert.informativeText = "The new version is installed. Notcholino restarts in about a second, and everything comes back as it was."
        alert.addButton(withTitle: "Restart now")
        alert.addButton(withTitle: "Later")
        NSApp.activate(ignoringOtherApps: true)
        if alert.runModal() == .alertFirstButtonReturn { relaunch() }
    }

    func remove(identifier: String) {
        pluginManager.remove(identifier: identifier)
        message = nil
    }

    // MARK: - Steps

    private func confirmInstall(_ plugin: RemotePlugin) -> Bool {
        let alert = NSAlert()
        alert.messageText = "Install \(plugin.name) \(plugin.version)?"
        alert.informativeText = """
        By \(plugin.author)

        \(plugin.description)

        Plugins run inside Notcholino with the same permissions as the app. \
        This one will be downloaded from the Notcholino releases on GitHub and checked against its published checksum.
        """
        alert.addButton(withTitle: "Install")
        alert.addButton(withTitle: "Cancel")
        NSApp.activate(ignoringOtherApps: true)
        return alert.runModal() == .alertFirstButtonReturn
    }

    /// Opens the app again once this one has quit (quitting also lets every plugin undo what it did)
    private func relaunch() {
        let path = Bundle.main.bundlePath
        let helper = Process()
        helper.executableURL = URL(fileURLWithPath: "/bin/sh")
        helper.arguments = ["-c", "sleep 1.5; /usr/bin/open \"$0\"", path]
        try? helper.run()
        NSApp.terminate(nil)
    }

    private func performInstall(_ plugin: RemotePlugin) async throws {
        guard plugin.url.absoluteString.hasPrefix(Self.allowedPrefix) else {
            throw StoreError.message("Refusing to download from an unknown location.")
        }

        let (tempFile, response) = try await URLSession.shared.download(from: plugin.url)
        guard (response as? HTTPURLResponse)?.statusCode == 200 else {
            throw StoreError.message("Download failed.")
        }

        // Verify the checksum before touching the zip
        let data = try Data(contentsOf: tempFile)
        let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        let expected = plugin.sha256.lowercased().replacingOccurrences(of: "sha256:", with: "")
        guard digest == expected else {
            throw StoreError.message("The download does not match its checksum, so it was discarded.")
        }

        // Unpack
        let work = FileManager.default.temporaryDirectory.appendingPathComponent("notcholino-plugin-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: work, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: work) }
        try unzip(tempFile, into: work)

        guard let bundleURL = try FileManager.default.contentsOfDirectory(at: work, includingPropertiesForKeys: nil)
            .first(where: { $0.pathExtension == "bundle" }) else {
            throw StoreError.message("The download does not contain a plugin.")
        }

        // Install (replacing a previous version)
        let wasLoaded = installedVersion(of: plugin.id) != nil
        let destination = pluginManager.bundleURL(forIdentifier: plugin.id)
        if FileManager.default.fileExists(atPath: destination.path) {
            try FileManager.default.removeItem(at: destination)
        }
        try FileManager.default.moveItem(at: bundleURL, to: destination)

        if wasLoaded {
            // The old code stays in memory until the app restarts
            // The old code stays in memory until the app restarts (two copies of a plugin's class can't live together),
            // so offer to restart right now: one click instead of quitting and reopening by hand
            message = "\(plugin.name) \(plugin.version) is installed and starts when Notcholino restarts."
            needsRestart.append(plugin.name)
            return
        }
        guard let loaded = pluginManager.load(bundleAt: destination), loaded.pluginIdentifier == plugin.id else {
            try? FileManager.default.removeItem(at: destination)
            throw StoreError.message("\(plugin.name) is not compatible with this version of Notcholino.")
        }
        message = nil
    }

    private func unzip(_ zip: URL, into directory: URL) throws {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/ditto")
        process.arguments = ["-x", "-k", zip.path, directory.path]
        try process.run()
        process.waitUntilExit()
        guard process.terminationStatus == 0 else { throw StoreError.message("Could not unpack the download.") }
    }

    private enum StoreError: Error {
        case message(String)
        var text: String { if case .message(let t) = self { return t } else { return "" } }
    }
}
